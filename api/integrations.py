"""Owner marketplace endpoints. Project and workspace credentials cannot access these routes."""
import os
from dataclasses import asdict
from typing import Literal
from uuid import UUID, uuid4

from fastapi import APIRouter, HTTPException, Request
from pydantic import BaseModel, Field

from github import repositories
from integration_registry import PROVIDERS, Probe, probe
from store import database
from vault import call

router = APIRouter(prefix="/integrations")


def get_provider(provider_id):
    provider = PROVIDERS.get(provider_id)
    if not provider:
        raise HTTPException(404, "Integration not found.")
    return provider


def default_status(provider_id, provider):
    if provider_id == "github" or provider.endpoint:
        return "NOT_CONNECTED"
    return "MANUAL_SETUP_REQUIRED"


@router.get("")
def directory():
    with database() as db:
        connections = {row["provider"]: row for row in db.execute("SELECT * FROM integration_connections")}
        steps = {}
        for row in db.execute("SELECT * FROM integration_setup ORDER BY step"):
            steps.setdefault((row["provider"], row["guide_version"]), []).append(row)
    entries = []
    for provider_id, provider in PROVIDERS.items():
        info = asdict(provider)
        for key in ("endpoint", "header", "prefix"):
            del info[key]
        coder = os.getenv("CODER_PUBLIC_URL", "").rstrip("/") if provider_id == "github" else ""
        entries.append({
            **info, "id": provider_id, "paste": bool(provider.endpoint),
            "authorize": coder + "/external-auth/github" if coder else None,
            "capability": "Discover installation repositories" if provider_id == "github" else provider.capability,
            "connection": connections.get(provider_id) or {"status": default_status(provider_id, provider)},
            "completed": steps.get((provider_id, provider.version), []),
        })
    return entries


@router.get("/activity")
def activity():
    with database() as db:
        return db.execute("SELECT * FROM integration_activity ORDER BY id DESC LIMIT 50").fetchall()


class Progress(BaseModel):
    version: int
    completed: bool


@router.put("/{provider_id}/guide/{step}")
def progress(provider_id: str, step: int, body: Progress):
    provider = get_provider(provider_id)
    if provider.version != body.version or not 1 <= step <= len(provider.steps):
        raise HTTPException(409, "Reload the current setup guide.")
    with database() as db:
        key = (provider_id, body.version, step)
        if body.completed:
            db.execute("INSERT INTO integration_setup (provider,guide_version,step) VALUES (%s,%s,%s) ON CONFLICT DO NOTHING", key)
        else:
            db.execute("DELETE FROM integration_setup WHERE provider=%s AND guide_version=%s AND step=%s", key)
    return {"ok": True}


def lock(db, provider_id):
    db.execute("SELECT pg_advisory_xact_lock(hashtext(%s)::bigint)", ("integration:" + provider_id,))


def record(db, provider_id, operation, result, save=True):
    if save:
        db.execute("""
            INSERT INTO integration_connections (provider,status,message,items,checked_at)
                VALUES (%s,%s,%s,%s,now())
            ON CONFLICT (provider) DO UPDATE SET
                status=EXCLUDED.status, message=EXCLUDED.message, items=EXCLUDED.items, checked_at=EXCLUDED.checked_at
        """, (provider_id, result.status, result.message, list(result.items)))
    db.execute("INSERT INTO integration_activity (provider,operation,status) VALUES (%s,%s,%s)",
               (provider_id, operation, result.status))
    return asdict(result)


@router.put("/{provider_id}/credential")
async def connect(provider_id: str, request: Request):
    from starlette.concurrency import run_in_threadpool
    provider = get_provider(provider_id)
    if not provider.endpoint:
        raise HTTPException(405, "Use the available setup method.")
    # Parse explicitly so autogenerated validation never echoes malformed credential input.
    raw = bytearray()
    async for chunk in request.stream():
        raw.extend(chunk)
        if len(raw) > 8192:
            raise HTTPException(413, "Credential input is too large.")
    try:
        import json
        value = json.loads(raw)["credential"]
        if not isinstance(value, str) or not 8 <= len(value) <= 4096 or any(not 33 <= ord(c) <= 126 for c in value):
            raise ValueError
    except (ValueError, TypeError, KeyError):
        raise HTTPException(422, "Enter a valid API key or token.") from None
    return await run_in_threadpool(validate_and_store, provider_id, value)


def validate_and_store(provider_id, value):
    with database() as db:
        lock(db, provider_id)
        result = probe(provider_id, value)
        if result.status != "OPERATIONAL":
            return record(db, provider_id, "credential-test", result, save=False)
        call("POST", f"data/integrations/{provider_id}", {"data": {"credential": value}})
        return record(db, provider_id, "credential-save", Probe("CONNECTED", result.message, result.items))


@router.post("/{provider_id}/verify")
def verify(provider_id: str):
    provider = get_provider(provider_id)
    with database() as db:
        lock(db, provider_id)
        if provider_id == "github":
            try:
                listing = repositories(1)
                result = (Probe("OPERATIONAL", "Installation repository discovery verified.", tuple(listing["repositories"]))
                          if listing["configured"] else Probe("CONFIGURATION_REQUIRED", "Configure the GitHub App installation."))
            except HTTPException:
                result = Probe("FAILED", "Repository discovery failed. Check GitHub App installation and server credentials.")
        elif provider.endpoint:
            secret = call("GET", f"data/integrations/{provider_id}", missing=True)
            result = (probe(provider_id, secret["data"]["data"]["credential"]) if secret
                      else Probe("NOT_CONNECTED", "Connect a credential first."))
        else:
            raise HTTPException(405, "Use the official verification procedure in the guide.")
        if result.status == "OPERATIONAL":
            result = Probe("CONNECTED", result.message, result.items)
        return record(db, provider_id, "verify", result)


@router.delete("/{provider_id}/credential")
def disconnect(provider_id: str):
    provider = get_provider(provider_id)
    if not provider.endpoint:
        raise HTTPException(405, "Manage this authorization through the provider.")
    with database() as db:
        lock(db, provider_id)
        call("DELETE", f"metadata/integrations/{provider_id}", missing=True)
        return record(db, provider_id, "disconnect", Probe("NOT_CONNECTED", "Credential removed from the marketplace vault."))


class ModelCheck(BaseModel):
    model: str = Field(min_length=1, max_length=200)
    project_id: UUID | None = None


class RoleAssignment(BaseModel):
    provider: Literal["openai", "anthropic", "codex_cli"]
    model: str | None = Field(default=None, max_length=200)
    project_id: UUID | None = None


def check_project(db, project_id):
    if project_id and not db.execute("SELECT id FROM projects WHERE id=%s AND NOT archived", (project_id,)).fetchone():
        raise HTTPException(404, "Active project not found.")


def check_model(db, provider, model):
    row = db.execute("SELECT items,status FROM integration_connections WHERE provider=%s", (provider,)).fetchone()
    if not row or row["status"] != "CONNECTED" or model not in row["items"]:
        raise HTTPException(409, "Verify the provider and select a discovered model.")


@router.get("/ai/settings")
def ai_settings():
    with database() as db:
        return {
            "roles": db.execute("SELECT scope,role,provider,model FROM integration_ai_role ORDER BY scope,role").fetchall(),
            "checks": db.execute("""SELECT project_id,provider,model,status,usage,checked_at
                FROM integration_ai_check ORDER BY checked_at DESC LIMIT 40""").fetchall(),
        }


@router.put("/ai/roles/{role}")
def set_role(role: Literal["prompter", "challenger", "coder", "reviewer"], body: RoleAssignment):
    if role == "coder":
        if body.provider != "codex_cli" or body.model is not None:
            raise HTTPException(422, "The coder uses the existing Codex CLI session.")
    elif body.provider == "codex_cli" or not body.model:
        raise HTTPException(422, "Select a separate API provider and model for this role.")
    with database() as db:
        check_project(db, body.project_id)
        if body.model:
            check_model(db, body.provider, body.model)
        db.execute("""INSERT INTO integration_ai_role (scope,role,provider,model) VALUES (%s,%s,%s,%s)
            ON CONFLICT (scope,role) DO UPDATE SET provider=EXCLUDED.provider,model=EXCLUDED.model""",
            (str(body.project_id or "global"), role, body.provider, body.model))
        db.execute("INSERT INTO integration_activity (provider,operation,status) VALUES (%s,%s,'CONFIGURATION_REQUIRED')",
                   (body.provider, "assign-" + role))
    return {"ok": True}


@router.post("/{provider_id}/verify-model")
def verify_model(provider_id: Literal["openai", "anthropic"], body: ModelCheck):
    from inference import ProviderFailure, run_model
    from psycopg.types.json import Jsonb
    with database() as db:
        lock(db, provider_id)
        check_project(db, body.project_id)
        check_model(db, provider_id, body.model)
        stored = call("GET", f"data/integrations/{provider_id}", missing=True)
        if not stored:
            raise HTTPException(409, "Connect this provider first.")
        try:
            _, usage = run_model(provider_id, body.model, stored["data"]["data"]["credential"],
                                 "This is a connectivity check. Reply with a short greeting.", "Hello.")
            result = Probe("OPERATIONAL", "Inference and token accounting verified.")
        except ProviderFailure as error:
            usage = None
            result = Probe("DEGRADED" if error.uncertain else "FAILED", str(error))
        db.execute("""INSERT INTO integration_ai_check (id, project_id, provider, model, status, usage)
            VALUES (%s,%s,%s,%s,%s,%s)""",
            (uuid4(), body.project_id, provider_id, body.model, result.status, Jsonb(usage) if usage else None))
        record(db, provider_id, "verify-inference", result, save=False)
    return {**asdict(result), "usage": usage}


class DnsInspection(BaseModel):
    zone: str = Field(min_length=1, max_length=253)


@router.post("/cloudflare/dns-inspection")
def inspect_cloudflare_dns(body: DnsInspection):
    import subprocess
    import httpx
    from dns_inspection import delegation, domain_name, matching_zone

    try:
        zone = domain_name(body.zone)
    except ValueError:
        raise HTTPException(422, "Enter a valid DNS zone name.") from None
    try:
        public_nameservers = delegation(zone)
    except (RuntimeError, ValueError, OSError, subprocess.TimeoutExpired):
        raise HTTPException(502, "DNS delegation lookup failed. Check resolver connectivity.") from None
    if not public_nameservers:
        raise HTTPException(409, "No NS answer for this name. Enter the delegated zone apex.")
    secret = call("GET", "data/integrations/cloudflare", missing=True)
    if not secret:
        raise HTTPException(409, "Connect a Cloudflare API token before inspecting its records.")
    key = secret["data"]["data"]["credential"]
    try:
        with httpx.Client(base_url="https://api.cloudflare.com/client/v4", timeout=8,
                          follow_redirects=False, trust_env=False, headers={"Authorization":"Bearer "+key}) as client:
            zones = client.get("/zones", params={"name":zone,"per_page":50})
            zones.raise_for_status()
            listing = zones.json()
            if listing.get("success") is not True:
                raise ValueError
            zone_id = matching_zone(zone, public_nameservers, listing["result"])
            if not zone_id:
                raise HTTPException(409, "Public NS answers do not match a unique active zone accessible to this token.")
            response = client.get(f"/zones/{zone_id}/dns_records", params={"per_page":100,"page":1})
            response.raise_for_status()
            payload = response.json()
            if payload.get("success") is not True:
                raise ValueError
            records = [{"name":row["name"],"type":row["type"],"ttl":row["ttl"]}
                       for row in payload["result"]]
            more = payload.get("result_info", {}).get("total_pages",1)>1
    except httpx.HTTPStatusError as error:
        if error.response.status_code in (401,403):
            raise HTTPException(403, "Check the token's Zone Read and DNS Read grants on this zone.") from None
        raise HTTPException(502, "Cloudflare could not complete the record lookup.") from None
    except (ValueError, KeyError, TypeError, httpx.RequestError):
        raise HTTPException(502, "Cloudflare record lookup could not be verified.") from None
    with database() as db:
        record(db,"cloudflare","inspect-dns",Probe("OPERATIONAL","Read delegate-matched DNS record metadata."),save=False)
    return {"zone":zone,"nameservers":public_nameservers,"records":records,"more":more}
